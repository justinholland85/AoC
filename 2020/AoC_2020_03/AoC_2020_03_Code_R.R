F.Part.1                    <-  function(Data){
  
  Data.Subs                 <-  gsub(Data, pattern = "\\.", replacement = 0)
  Data.Subs                 <-  gsub(Data.Subs, pattern = "#",   replacement = 1)
  
  Trees                     <-  lapply(strsplit(Data.Subs, ""), as.numeric)
  
  N.Pattern                 <-  length(Trees[[1]])        
  
  ID                        <-  seq(1, length(Trees))
  
  dX                        <-  3
  
  Ref.X                     <-  (1 + (ID - 1) * dX) %% N.Pattern
  Ref.X[which(Ref.X == 0)]  <-  N.Pattern
  
  HitTree                   <-  mapply(Lib.Take.One, Trees, as.list(Ref.X))
  
  N.Trees.Hit               <-  sum(HitTree[-1])
  
  return(N.Trees.Hit)
  
}

