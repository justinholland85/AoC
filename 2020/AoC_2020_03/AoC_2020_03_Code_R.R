F.Part.2                    <-  function(Data){
  
  Data.Subs                 <-  gsub(Data, pattern = "\\.", replacement = 0)
  Data.Subs                 <-  gsub(Data.Subs, pattern = "#",   replacement = 1)
  
  Trees                     <-  lapply(strsplit(Data.Subs, ""), as.numeric)
  N.Pattern                 <-  length(Trees[[1]])    
  
  Height                    <-  length(Trees)

  
  Slopes                    <-  list(c(1,1),
                                     c(3,1), 
                                     c(5,1), 
                                     c(7,1), 
                                     c(1,2)) 
  
  #----------------------------------------------------------------------------------------------------#
  # F.PathWay
  #----------------------------------------------------------------------------------------------------#
  
  F.PathWay   <-  function(Vec){
    
    Pos      <-  c(1,1)  
    
    PathWay  <-  list()
    i        <-  1
    
    repeat{
      
      Pos   <-  Pos + Vec
      
      if(Pos[2] > Height){break} else {PathWay[[i]] <- Pos; i <- i + 1}
      
      
    }
    
    
   Path.X    <-  unlist(lapply(PathWay, Lib.Take.One, 1)) %% N.Pattern
   Path.X[which(Path.X == 0)]  <-  N.Pattern
   
   Path.Y    <-  unlist(lapply(PathWay, Lib.Take.One, 2))
   
   HitTree   <-  mapply(Lib.Take.One, Trees[Path.Y], as.list(Path.X))
   
   N.Trees.Hit               <-  sum(HitTree)
   
   return(N.Trees.Hit)
   
    
  }
  
  #----------------------------------------------------------------------------------------------------#
  # Loop
  #----------------------------------------------------------------------------------------------------#

  N.Trees.Hit             <-  lapply(Slopes, F.PathWay)
  
  TreeProduct             <-  prod(unlist(N.Trees.Hit))
  
  return(TreeProduct)
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#

F.Part.2(Data.0)
F.Part.2(Data.1)

















