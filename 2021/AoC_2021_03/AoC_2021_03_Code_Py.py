def F_Part_2(Data): 
    
    Mat         = np.array([list(x) for x in Data], dtype=int)
    N           = len(Mat[0])

    #----------------------------------------------------------------------------------------------------#
    # F_Choose
    #----------------------------------------------------------------------------------------------------#

    def F_Choose(Gas):

        X = Mat

        for i in range(N):

            Mean     = np.mean(X[:,i])

            Dominant = 1 * (Mean >= .5)

            if Gas == "CO2":
                Req = 1 - Dominant
            else:
                Req = Dominant

            X = X[X[:,i] == Req]  

            if len(X) == 1:
                break

        Decimal = np.sum(X   * (2 ** np.arange(N-1, -1, -1)))

        return Decimal

    #----------------------------------------------------------------------------------------------------#
    # Execute
    #----------------------------------------------------------------------------------------------------#

    Oxygen      = F_Choose("Oxygen")
    CO2         = F_Choose("CO2")

    LifeSupport = Oxygen * CO2

    return LifeSupport
    
