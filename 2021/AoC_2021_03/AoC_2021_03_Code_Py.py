def F_Part_1(Data): 

    Mat         = np.array([list(x) for x in Data], dtype=int)

    Mean        = np.mean(Mat, axis=0)

    Gamma       =  1 * (Mean > .5)
    Epsilon     =  1 * (Mean < .5)

    N           = len(Gamma)

    Gamma_Dec   = sum(Gamma   * (2 ** np.arange(N-1, -1, -1)))
    Epsilon_Dec = sum(Epsilon * (2 ** np.arange(N-1, -1, -1)))

    Power       = Gamma_Dec * Epsilon_Dec

    return Power


