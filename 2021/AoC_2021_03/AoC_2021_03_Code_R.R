F.Part.2                    <-  function(Data){
  
  Mat         <-  do.call(rbind, lapply(strsplit(Data, ""), as.numeric))
  N           <-  ncol(Mat)
  
  #----------------------------------------------------------------------------------------------------#
  # F.Choose
  #----------------------------------------------------------------------------------------------------#
  
  F.Choose    <-  function(Gas){
  
    X    <-  Mat

    for(i in 1:N){
     
      Mean       <-  mean(X[,i])

      Dominant   <-  1 * (Mean >= .5)
      
      Req        <-  ifelse(Gas == "CO2", 1 - Dominant, Dominant)
      
      X          <-  X[X[,i] == Req,, drop = FALSE]
      
      if(nrow(X) == 1){break}
      
    }
    
    Decimal  <- sum(X * 2 ^ seq(N-1, 0))
    
    return(Decimal)
    
  }

  #----------------------------------------------------------------------------------------------------#
  # Execute
  #----------------------------------------------------------------------------------------------------#
  
  Oxygen       <-  F.Choose("Oxygen")
  CO2          <-  F.Choose("CO2")
  
  
  LifeSupport  <-  Oxygen * CO2
  
  return(LifeSupport)
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#

F.Part.2(Data.0)
F.Part.2(Data.1)
