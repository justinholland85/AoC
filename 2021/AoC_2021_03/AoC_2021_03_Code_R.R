F.Part.1                    <-  function(Data){
  
  Mat         <-  do.call(rbind, lapply(strsplit(Data, ""), as.numeric))
  
  Mean        <-  apply(Mat, 2, mean)
  
  Gamma       <-  1 * (Mean > .5)
  Epsilon     <-  1 * (Mean < .5)
  
  N           <-  length(Gamma)
  
  Gamma.Dec   <-  sum(Gamma * 2 ^ seq(N-1, 0))
  Epsilon.Dec <-  sum(Epsilon * 2 ^ seq(N-1, 0))
  
  Power       <-  Gamma.Dec  * Epsilon.Dec
  
  return(Power)
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#

