# Data   <-  Data.1

F.Part.1   <-  function(Data){

  Priority  <-  c(letters, LETTERS)
  Score     <-  0

  for (i in seq_along(Data)) {

    Items        <-  strsplit(Data[i], split = "")[[1]]
    Compartment  <-  length(Items) / 2
    Common       <-  intersect(Items[1:Compartment], Items[(Compartment + 1):length(Items)])
    Score        <-  Score + match(Common, Priority)

  }

  return(Score)

}


#====================================================================================================#
# Execute
#====================================================================================================#

F.Part.1(Data.0)
F.Part.1(Data.1)


