F.Part.2   <-  function(Data){

  Priority     <-  c(letters, LETTERS)
  Group.Start  <-  seq(1, length(Data), by = 3)
  Score        <-  0

  for (i in Group.Start) {

    Group   <-  lapply(Data[i:(i + 2)], function(Rucksack) strsplit(Rucksack, split = "")[[1]])
    Common  <-  Reduce(intersect, Group)
    Score   <-  Score + match(Common, Priority)

  }

  return(Score)

}


#====================================================================================================#
# Execute
#====================================================================================================#

F.Part.2(Data.0)
F.Part.2(Data.1)
