F.Part.1                    <-  function(Data){
  
  PrioritySpec   <-  c(letters, LETTERS)
  Nchar          <-  nchar(Data)
  Comp.1         <-  strsplit(substr(Data, 1, Nchar / 2), "")
  Comp.2         <-  strsplit(substr(Data, Nchar / 2 + 1, Nchar), "")
  
  Intersect      <-  mapply(intersect, Comp.1, Comp.2)
  
  Priority       <-  match(Intersect, PrioritySpec)
  
  Priority.Sum   <-  sum(Priority)
  
  return(Priority.Sum)
  
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#

