F.Part.2                    <-  function(Data){
  
  PrioritySpec   <-  c(letters, LETTERS)
  
  Split          <-  strsplit(Data, "")
  
  Group          <-  ceiling(seq(1, length(Data)) / 3)
  
  Sets           <-  tapply(Split, Group, c)

  Intersect      <-  unlist(lapply(Sets, Reduce, f = intersect))
  
  Priority       <-  match(Intersect, PrioritySpec)
  
  Priority.Sum   <-  sum(Priority)
  
  return(Priority.Sum)
  
  
}

#====================================================================================================#
# Execution  
#====================================================================================================#

F.Part.2(Data.0)
F.Part.2(Data.1)







