F.Part.2          <-  function(Data){
  
  Split           <-  lapply(strsplit(gsub(" {2,}", " ",  trimws(Data)), " "), as.numeric)
  Matrix          <-  do.call(rbind, Split)     
  Vector          <-  c(Matrix)
  Triangles       <-  tapply(Vector, ceiling(seq_along(Vector) / 3)  ,c)
  
  
  
  F.Valid.Triangle   <-  function(X){
    
    A  <- X[1]
    B  <- X[2]
    C  <- X[3]
    
    Valid  <-  (A + B  > C) & (A + C > B) & (B + C > A) 
    
    return(Valid)
    
  }
  

  Triangles.Valid   <- unlist(lapply(Triangles,F.Valid.Triangle))
  
  
  Possible   <-  sum(Triangles.Valid)
  
  return(Possible)
  
}

