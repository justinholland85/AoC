# F.Sub.1
#====================================================================================================#
# Sub.1 cleans the ranges into proper intervals

F.Sub.1  <-  function(A, B){
  
  options(warn = -1)
  
  Order    <-  order(A, B)
  
  A      <-  A[Order]
  B      <-  B[Order]
  
  N      <-  length(A)
  
  Mod.A  <-  numeric(0)
  Mod.B  <-  numeric(0)
  

  for(i in  1:N){
   
  n  <-  length(Mod.A)
    
  A.0    <-  max(Mod.A)
  B.0    <-  max(Mod.B)
   
  A.1   <-  A[i]
  B.1   <-  B[i]
  

  if(A.0 <= A.1 & A.1 <= B.0){
    
    Mod.A[n]  <-  A.0
    Mod.B[n]  <-  max(B.0, B.1)
    Mod.B[n ] <-  max(B.0, B.1)
    
  }  else {
    
    n         <-  n + 1
    Mod.A[n]  <-  A.1
    Mod.B[n]  <-  B.1
 
  } 
  
  
  }
  
  DF    <-  data.frame(A = Mod.A, 
                       B = Mod.B)
  
  return(DF)
    
}


#====================================================================================================#
# F.Part.1
#====================================================================================================#

F.Part.1  <-  function(Data){
  
  
  #-- Data setup
  
  Ranges         <-  grep(Data, pattern = "-", value = TRUE )
  Values         <-  as.numeric(setdiff(Data, Ranges))
  
  Ranges         <-  data.frame(do.call(rbind, strsplit(Ranges, split = "-")))
  Ranges         <-  data.frame(lapply(Ranges, as.numeric))
  names(Ranges)  <-  c("A", "B")
  
  #-- Tidy Ranges
  
  Clean          <-  F.Sub.1(Ranges$A, 
                             Ranges$B + 1)
  
  Breaks         <-  c(-Inf, t(as.matrix(Clean)), Inf)
  
  
  #-- Assign interval
  
  Interval    <-  Lib.RangeMap(Values, Breaks)
  
  Fresh       <-  Interval %% 2 == 0
  
  return(sum(Fresh))
  
  
}


