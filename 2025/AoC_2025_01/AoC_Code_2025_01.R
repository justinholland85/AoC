F.Part.1   <-  function(Data, X0, N){
  
  Direction   <-  substr(Data,1,1)
  Move        <-  as.numeric(substr(Data,2,nchar(Data)))
  
  dX          <-  Move * (-1)^(Direction == "L")
  X           <-  (X0 + cumsum(dX)) %% N
   
  return(sum(X == 0))
  
}

