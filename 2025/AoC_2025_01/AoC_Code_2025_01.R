Data          <-  Data.0
X0            <-  50
N             <-  100

F.Part.2   <-  function(Data, X0, N){
  
  Direction   <-  substr(Data,1,1)
  Move        <-  as.numeric(substr(Data,2,nchar(Data)))
  
  Lambda      <-  length(Data) + 1
  
  dX          <-  Move * (-1)^(Direction == "L")
  X           <-  c(X0, (X0 + cumsum(dX)) %% N)
  
  FullRots    <-  floor(Move/ N)  
  
  Remainder   <-  Move %% N
  
  Pass        <-  (Direction == "L") * (Remainder > X[-Lambda]) +
                  (Direction == "R") * (Remainder > ((N - X[-Lambda]) %% 100))

  
  DF          <-  data.frame(X, dX = c(dX, NA), Pass = c(Pass,NA))

  return(sum(c(Pass, FullRots, X[Lambda] == 0 )))
  
}

# Note: We do not need to count the landings at zero explictly as they get pick up as a Pass on the 
#       next step implicitly, except where the very final landing spot happens to be zero.

#====================================================================================================#
# Execution  
#====================================================================================================#


F.Part.2(Data.0, 50, 100)
