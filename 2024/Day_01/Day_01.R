Data   <-  Data.Input

F.Part.2   <-  function(Data){
  
  X1          <-  sort(Data$X1)
  X2          <-  sort(Data$X2)

  Table.X2    <-  table(X2)
  
  Multiplier  <-  Lib.NA.To.Zero(as.numeric(Table.X2[match(X1, Lib.NumericNames(Table.X2))]))
  
  return(sum(X1 * Multiplier))
  
  
}


#====================================================================================================#
# Execute
#====================================================================================================#

F.Part.2(Data.Example)
F.Part.2(Data.Input)




