F.Part.2                    <-  function(Data){
  
  X        <-  paste(Data, collapse = "")
  
  #--------------------------------------------------------------------------------------------------#
  # Base Info
  #--------------------------------------------------------------------------------------------------#
  
  Pattern  <-  "mul\\(([0-9]{1,3}),([0-9]{1,3})\\)"
  
  Matches  <-  gregexpr(Pattern, X, perl = TRUE)
  Found    <-  regmatches(X, Matches)[[1]]
  
  Numbers  <-  strcapture(
    Pattern,
    Found,
    proto = list(X = integer(), Y = integer())
  )
  
  Numbers$Start   <-  as.numeric(Matches[[1]])

  
  #--------------------------------------------------------------------------------------------------#
  # do() and don't() handles
  #--------------------------------------------------------------------------------------------------#

  Matches.Do    <-  as.numeric(gregexpr("do\\(\\)", X, perl = TRUE)[[1]])
  Matches.Dont  <-  as.numeric(gregexpr("don't\\(\\)", X, perl = TRUE)[[1]])

  OnOff         <-  data.frame(Pos = sort(unique(c(0,Matches.Do, Matches.Dont))))
  
  OnOff$Switch  <-  ifelse(OnOff$Pos %in% Matches.Dont, -1, 1)
  OnOff$Change  <-  1 * (c(0, OnOff$Switch[-nrow(OnOff)]) != OnOff$Switch)
  
  OnOff         <-  OnOff[which(OnOff$Change == 1),]
  OnOff$Seq     <-  seq(1, nrow(OnOff)) 

  # 
  
  On            <-  OnOff$Pos[OnOff$Seq %% 2 == 1]
  Off           <-  c(OnOff$Pos[OnOff$Seq %% 2 == 0], Inf)
  
  #--------------------------------------------------------------------------------------------------#
  # Range Check
  #--------------------------------------------------------------------------------------------------#
  
  N             <-  length(On)
  
  Numbers$On    <-  0
  
  for(i in 1:N){
    
    Numbers$On  <-  Numbers$On + (On[i] < Numbers$Start & Numbers$Start < Off[i])  
    
  }
  
  #--------------------------------------------------------------------------------------------------#
  # Result
  #--------------------------------------------------------------------------------------------------#
  
  SumProd       <-  sum(Numbers$X * Numbers$Y * Numbers$On)
  
  return(SumProd)
  
}


#====================================================================================================#
# Execute
#====================================================================================================#

F.Part.2(Data.0a)
F.Part.2(Data.1)











