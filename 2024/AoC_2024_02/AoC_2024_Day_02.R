#====================================================================================================#
# F.p1.Delta
#====================================================================================================#

X  <-  Data.Example[[1]]

F.p1.Delta  <-  function(X){
  
  
  Delta    <-  X[-1] - X[-length(X)]
  return(Delta)
  
  
}




#====================================================================================================#
# F.p1.Tests
#====================================================================================================#

dX            <-  F.p1.Delta(X)
r.Min         <-  1
r.Max         <-  3 

F.p1.Tests    <-  function(dX, r.Min, r.Max){
  
  
  Test.Sign     <-  prod(sign(dX) == sign(dX[[1]])) == 1
  
  Test.Mag      <-  prod(r.Min <= abs(dX) & abs(dX) <= r.Max) == 1
  
  
  Test          <-  Test.Sign & Test.Mag    
  
  return(Test)
  
}  



#====================================================================================================#
# F.Part.1
#====================================================================================================#
Data    <-  Data.Example

r.Min         <-  1
r.Max         <-  3 

F.Part.1   <-  function(Data, r.Min, r.Max){
 
  dX      <-  lapply(Data, F.p1.Delta)  
  Test    <-  unlist(lapply(dX, F.p1.Tests,  r.Min, r.Max )) 
  
  return(sum(Test))
}

