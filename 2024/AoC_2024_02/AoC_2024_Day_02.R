#====================================================================================================#
# F.p2.Extend
#====================================================================================================#

F.p2.Extend     <-  function(X){
  
  List    <-  list(X)
  
  for(i in 1:length(X)){
    
    List[[i+1]]  <-  X[-i]
    
  }
  
  return(List)
  
  
}


#====================================================================================================#
# F.p2.Extend.Wrap
#====================================================================================================#

F.p2.Extend(Data[[1]])

F.p2.Extend.Wrap   <-  function(Data){
  
  
  Lists      <-  lapply(Data, F.p2.Extend)
  Length     <-  unlist(lapply(Lists, length))
  Data.Long  <-  do.call(c, Lists)
  ID         <-  rep(seq(1, length(Data)), Length)
  
  Output     <-  list(Data.Long = Data.Long, 
                      ID        = ID)
  return(Output)
  
}



#====================================================================================================#
# F.Part.2
