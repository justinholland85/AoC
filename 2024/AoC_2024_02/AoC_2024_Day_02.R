F.Part.2   <-  function(Data, r.Min, r.Max){
  
  Extend     <-  F.p2.Extend.Wrap(Data)
  
  Data.Long  <-  Extend$Data.Long
  ID         <-  Extend$ID
  
  dX         <-  lapply(Data.Long, F.p1.Delta)  
  Test       <-  unlist(lapply(dX, F.p1.Tests,  r.Min, r.Max )) 
  
  
  return(length(unique(ID[Test])))
  
}



